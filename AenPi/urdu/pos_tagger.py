def _char_ngrams(word: str, n: int) -> list[str]:
    return [word[i:i+n] for i in range(len(word) - n + 1)]


def word_features(sent: list[str], i: int) -> dict:
    """
    Feature dict for word at position i in sentence.
    Uses current word, ±2 context words, prefixes/suffixes.
    """
    word = sent[i]
    feats = {
        "bias":         1.0,
        "word":         word,
        "word.lower":   word.lower(),
        "word[-3:]":    word[-3:],
        "word[-2:]":    word[-2:],
        "word[:3]":     word[:3],
        "word[:2]":     word[:2],
        "word.len":     len(word),
        "word.isdigit": word.isdigit(),
    }

    # character bigrams & trigrams
    for bg in _char_ngrams(word, 2):
        feats[f"word.bg={bg}"] = True
    for tg in _char_ngrams(word, 3):
        feats[f"word.tg={tg}"] = True

    # context: -2, -1, +1, +2
    for offset, label in [(-2, "w-2"), (-1, "w-1"), (1, "w+1"), (2, "w+2")]:
        idx = i + offset
        if 0 <= idx < len(sent):
            ctx = sent[idx]
            feats.update({
                f"{label}":       ctx,
                f"{label}[-3:]":  ctx[-3:],
                f"{label}[:3]":   ctx[:3],
            })
        else:
            feats[f"{label}.BOS_EOS"] = True

    # sentence-boundary flags
    if i == 0:
        feats["BOS"] = True
    if i == len(sent) - 1:
        feats["EOS"] = True

    return feats


def sent_to_features(sent: list[str]) -> list[dict]:
    return [word_features(sent, i) for i in range(len(sent))]

def sent_to_labels(sent: list[tuple[str, str]]) -> list[str]:
    return [tag for _, tag in sent]

def sent_to_tokens(sent: list[tuple[str, str]]) -> list[str]:
    return [w for w, _ in sent]


