def read_conllu(path: str) -> list[list[tuple[str, str]]]:
    """
    Parse a CoNLL-U file.
    Returns list of sentences, each sentence = list of (word, upos) tuples.
    Multi-word tokens (lines with '-') and empty nodes ('.' ids) are skipped.
    """
    sentences, current = [], []
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            line = line.rstrip("\n")
            if line.startswith("#"):
                continue
            if line == "":
                if current:
                    sentences.append(current)
                    current = []
                continue
            cols = line.split("\t")
            if len(cols) < 4:
                continue
            tok_id = cols[0]
            if "-" in tok_id or "." in tok_id:   # skip MWT / empty nodes
                continue
            word = cols[1]
            upos = cols[3]
            if upos == "_":
                continue
            current.append((word, upos))
    if current:
        sentences.append(current)
    return sentences


