UDTB_BASE = "https://raw.githubusercontent.com/UniversalDependencies/UD_Urdu-UDTB/master"
UDTB_FILES = {
    "train": "ur_udtb-ud-train.conllu",
    "dev":   "ur_udtb-ud-dev.conllu",
    "test":  "ur_udtb-ud-test.conllu",
}

def download_udtb(dest_dir: str = "udtb_data") -> dict[str, str]:
    """
    Download the three CoNLL-U splits of UD Urdu UDTB.
    Returns dict {split: local_path}.
    """
    os.makedirs(dest_dir, exist_ok=True)
    paths = {}
    for split, fname in UDTB_FILES.items():
        local = os.path.join(dest_dir, fname)
        if not os.path.exists(local):
            url = f"{UDTB_BASE}/{fname}"
            print(f"Downloading {split} split → {local}")
            urllib.request.urlretrieve(url, local)
        else:
            print(f"[cache] {split} split already at {local}")
        paths[split] = local
    return paths


