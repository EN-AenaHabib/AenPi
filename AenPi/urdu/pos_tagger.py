class UrduPOSTagger:
    """
    CRF-based Urdu POS tagger trained on UD Urdu Treebank.

    Training
    --------
    >>> tagger = UrduPOSTagger()
    >>> tagger.train("udtb_data/ur_udtb-ud-train.conllu",
    ...              "udtb_data/ur_udtb-ud-dev.conllu")
    >>> tagger.evaluate("udtb_data/ur_udtb-ud-test.conllu")
    >>> tagger.save("urdu_pos_crf.pkl")

    Inference
    ---------
    >>> tagger = UrduPOSTagger.load("urdu_pos_crf.pkl")
    >>> tagger.tag("میں کتاب پڑھتا ہوں".split())
    """

    def __init__(self):
        self.model = None
        self.labels: list[str] = []

    # ------------------------------------------------------------------
    # Training
    # ------------------------------------------------------------------

    def train(
        self,
        train_path: str,
        dev_path: str   = "",
        *,
        max_iterations: int = 200,
        c1: float = 0.1,
        c2: float = 0.1,
    ):
        crfsuite = _require("sklearn_crfsuite", "sklearn-crfsuite")
        CRF = crfsuite.CRF

        print("Reading training data …")
        train_sents = read_conllu(train_path)
        print(f"  {len(train_sents):,} training sentences")

        X_train = [sent_to_features(sent_to_tokens(s)) for s in train_sents]
        y_train = [sent_to_labels(s)                   for s in train_sents]

        self.labels = sorted({tag for s in train_sents for _, tag in s})

        print(f"Labels ({len(self.labels)}): {self.labels}")
        print("Training CRF …")

        self.model = CRF(
            algorithm="lbfgs",
            c1=c1,
            c2=c2,
            max_iterations=max_iterations,
            all_possible_transitions=True,
        )
        self.model.fit(X_train, y_train)
        print("Training complete.")

        if dev_path:
            print("\n--- Dev evaluation ---")
            self.evaluate(dev_path)

    # ------------------------------------------------------------------
    # Evaluation
    # ------------------------------------------------------------------

    def evaluate(self, conllu_path: str) -> dict:
        metrics = _require("sklearn_crfsuite.metrics", "sklearn-crfsuite")
        flat_f1 = _require("sklearn_crfsuite.metrics", "sklearn-crfsuite")

        from sklearn_crfsuite import metrics as crf_metrics
        from sklearn.metrics import accuracy_score

        sents = read_conllu(conllu_path)
        X = [sent_to_features(sent_to_tokens(s)) for s in sents]
        y_true = [sent_to_labels(s)              for s in sents]
        y_pred = self.model.predict(X)

        # flat accuracy
        flat_true = [t for seq in y_true for t in seq]
        flat_pred = [t for seq in y_pred for t in seq]
        acc = accuracy_score(flat_true, flat_pred)

        print(f"Token accuracy : {acc*100:.2f}%")
        print()
        print(crf_metrics.flat_classification_report(
            y_true, y_pred, labels=self.labels, digits=4
        ))

        return {"accuracy": acc, "y_true": flat_true, "y_pred": flat_pred}

    # ------------------------------------------------------------------
    # Inference
    # ------------------------------------------------------------------

    def tag(self, tokens: list[str]) -> list[tuple[str, str]]:
        """POS-tag a pre-tokenized list of Urdu tokens."""
        if self.model is None:
            raise RuntimeError("Model not trained/loaded. Call train() or load().")
        feats  = sent_to_features(tokens)
        tags   = self.model.predict([feats])[0]
        return list(zip(tokens, tags))

    def tag_sentence(self, sentence: str) -> list[tuple[str, str]]:
        """Convenience wrapper: splits on whitespace then tags."""
        return self.tag(sentence.split())

    # ------------------------------------------------------------------
    # Persist
    # ------------------------------------------------------------------

    def save(self, path: str = "urdu_pos_crf.pkl"):
        with open(path, "wb") as f:
            pickle.dump({"model": self.model, "labels": self.labels}, f)
        print(f"Model saved → {path}")

    @classmethod
    def load(cls, path: str = "urdu_pos_crf.pkl") -> "UrduPOSTagger":
        inst = cls()
        with open(path, "rb") as f:
            data = pickle.load(f)
        inst.model  = data["model"]
        inst.labels = data["labels"]
        print(f"Model loaded ← {path}")
        return inst


